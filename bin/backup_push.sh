#!/usr/bin/env bash
# Push one station snapshot to the private backup repository.
#
# Design notes:
# - The lock makes runs queue-safe: a second invocation exits 0 instead of
#   overlapping, so an automation with overlap_policy=queue can never corrupt a
#   snapshot or race the push.
# - Credentials are read from config/db_local.json (untracked) and passed through
#   PGPASSWORD; nothing secret is written to disk, argv, or stdout.
# - brain/workstation.db is deliberately excluded: the PostgreSQL dump already
#   contains that state, and the file is 23 MB of duplicated pages.
# - Snapshots are pruned to the newest N so the private repo stays small.
set -euo pipefail

STATION="${STATION_HOME:-$HOME/.ai-station}"
WORK="${STATION_BACKUP_REPO:-$HOME/runtime/backup-repo}"
LOCK="${STATION_BACKUP_LOCK:-$HOME/runtime/backup-repo.lock}"
KEEP="${STATION_BACKUP_KEEP:-14}"
REMOTE="${STATION_BACKUP_REMOTE:-origin}"
BRANCH="${STATION_BACKUP_BRANCH:-main}"
GIT_NAME="${STATION_BACKUP_GIT_NAME:-AI Station Backup}"
GIT_EMAIL="${STATION_BACKUP_GIT_EMAIL:-backup@irsofka.co.id}"

say() { printf 'backup: %s\n' "$*"; }
die() { printf 'backup: %s\n' "$*" >&2; exit 1; }

command -v pg_dump >/dev/null || die "pg_dump not found"
command -v tar >/dev/null || die "tar not found"
command -v git >/dev/null || die "git not found"
command -v rsync >/dev/null || die "rsync not found"

mkdir -p "$(dirname "$LOCK")"
exec 9>"$LOCK"
if ! flock -n 9; then
  say "another run holds the lock; skipping this tick (queue mode)"
  exit 0
fi

[ -d "$WORK/.git" ] || die "backup repo not initialised at $WORK"
[ -f "$STATION/config/db_local.json" ] || die "missing $STATION/config/db_local.json"

read -r DBH DBP DBU DBN <<<"$(python3 - "$STATION/config/db_local.json" <<'PY'
import json, sys
doc = json.load(open(sys.argv[1]))
print(doc["host"], doc["port"], doc["user"], doc["dbname"])
PY
)"
PGPASSWORD="$(python3 - "$STATION/config/db_local.json" <<'PY'
import json, sys
print(json.load(open(sys.argv[1]))["password"])
PY
)"
export PGPASSWORD

ts="$(date -u +%Y%m%dT%H%M%SZ)"
mkdir -p "$WORK/db" "$WORK/brain"

say "dumping database $DBN"
pg_dump -h "$DBH" -p "$DBP" -U "$DBU" -d "$DBN" --no-owner --no-privileges \
  | gzip -6 > "$WORK/db/station-$ts.sql.gz"
unset PGPASSWORD

say "archiving memory, skills, rules"
BRAIN_PATHS=(.ai-station/brain/memory .ai-station/brain/skills .ai-station/brain/rules)
for extra in .ai-station/brain/DESIGN_NOTES.md .ai-station/brain/IDENTITY.md .ai-station/brain/schema_postgresql.sql; do
  [ -e "$HOME/$extra" ] && BRAIN_PATHS+=("$extra")
done
tar -czf "$WORK/brain/brain-$ts.tar.gz" -C "$HOME" "${BRAIN_PATHS[@]}"

# Konten dan media situs dicerminkan sebagai berkas, bukan arsip: git hanya
# menyimpan blob yang benar-benar baru, jadi media ber-sha tetap murah.
# Thumbnail tidak ikut — dibuat ulang oleh tools/site/build.py.
say "syncing site content and media"
SITE_SRC="$STATION/site"
mkdir -p "$WORK/site/content" "$WORK/site/media"
if [ -d "$SITE_SRC/content" ]; then
  rsync -a --delete "$SITE_SRC/content/" "$WORK/site/content/"
fi
if [ -d "$SITE_SRC/media" ]; then
  rsync -a --delete --exclude '_thumbs/' "$SITE_SRC/media/" "$WORK/site/media/"
fi
site_files="$(find "$WORK/site" -type f 2>/dev/null | wc -l)"
site_bytes="$(du -sb "$WORK/site" 2>/dev/null | cut -f1)"
say "site: $site_files files, $site_bytes bytes"

db_bytes="$(stat -c%s "$WORK/db/station-$ts.sql.gz")"
brain_bytes="$(stat -c%s "$WORK/brain/brain-$ts.tar.gz")"
db_sha="$(sha256sum "$WORK/db/station-$ts.sql.gz" | cut -d' ' -f1)"
brain_sha="$(sha256sum "$WORK/brain/brain-$ts.tar.gz" | cut -d' ' -f1)"

cat > "$WORK/MANIFEST.md" <<EOF
# Latest snapshot

- taken at (UTC): $ts
- database: \`db/station-$ts.sql.gz\` — $db_bytes bytes, sha256 \`$db_sha\`
- brain (memory, skills, rules, docs): \`brain/brain-$ts.tar.gz\` — $brain_bytes bytes, sha256 \`$brain_sha\`
- site content/media: \`site/content/\`, \`site/media/\` — $site_files files, $site_bytes bytes (thumbnails excluded, regenerated by build)
- excluded on purpose: \`brain/workstation.db\` (already inside the SQL dump)

Restore the database with:

\`\`\`bash
gunzip -c db/station-$ts.sql.gz | psql -d irsofka_ai_workstation
\`\`\`

Restore site content and media with:

\`\`\`bash
rsync -a site/content/ ~/.ai-station/site/content/
rsync -a site/media/ ~/.ai-station/site/media/
python3 ~/.ai-station/tools/site/build.py
\`\`\`
EOF

# Keep only the newest $KEEP snapshots per directory.
prune() {
  local dir="$1" pattern="$2"
  mapfile -t old < <(ls -1t "$dir"/$pattern 2>/dev/null | tail -n +$((KEEP + 1)))
  if [ "${#old[@]}" -gt 0 ]; then
    say "pruning ${#old[@]} old snapshot(s) in ${dir##*/}"
    rm -f -- "${old[@]}"
  fi
}
prune "$WORK/db" 'station-*.sql.gz'
prune "$WORK/brain" 'brain-*.tar.gz'

cd "$WORK"
git add -A
if git diff --cached --quiet; then
  say "nothing changed since the last snapshot"
else
  git -c user.name="$GIT_NAME" -c user.email="$GIT_EMAIL" \
    commit -q -m "snapshot $ts" -m "db=${db_bytes}B brain=${brain_bytes}B site=${site_files}f"
fi

# Rebase before pushing: the repo may have been touched from another machine.
git -c user.name="$GIT_NAME" -c user.email="$GIT_EMAIL" pull --rebase --autostash -q "$REMOTE" "$BRANCH" 2>/dev/null || true
git push -q "$REMOTE" "HEAD:$BRANCH"
say "pushed snapshot $ts to $REMOTE/$BRANCH"
